import type { Timeframe } from '../types/terminal';

// Allowed timeframes whitelist
const VALID_TIMEFRAMES: ReadonlySet<Timeframe> = new Set<Timeframe>([
  '1s',
  '1m',
  '5m',
  '15m',
  '1h',
  '4h',
  '1d',
]);

// Prototype pollution forbidden property names
const FORBIDDEN_KEYS: ReadonlySet<string> = new Set<string>([
  '__proto__',
  'constructor',
  'prototype',
]);

/**
 * Validates and sanitizes a trading instrument symbol.
 * Allows only alphanumeric characters, underscores, hyphens, equals, periods, and caret symbols.
 * Caps length at 24 characters.
 */
export function sanitizeSymbol(input: unknown): string {
  if (typeof input !== 'string') return 'BTCUSDT';
  const trimmed = input.trim();
  if (!trimmed || FORBIDDEN_KEYS.has(trimmed.toLowerCase())) {
    return 'BTCUSDT';
  }

  // Whitelist safe symbol characters (supports crypto, stocks with NS/BO, indexes ^NSEI, forex EURUSD=X)
  const cleaned = trimmed.replace(/[^A-Za-z0-9_=\-\.\^]/g, '').slice(0, 24);
  return cleaned || 'BTCUSDT';
}

/**
 * Validates timeframe against whitelist or safe custom interval format (e.g. 2m, 10m, 45m, 2h, 3d, 1w, 1M).
 */
export function sanitizeTimeframe(input: unknown): Timeframe {
  if (typeof input === 'string') {
    const trimmed = input.trim();
    if (VALID_TIMEFRAMES.has(trimmed as Timeframe)) {
      return trimmed as Timeframe;
    }
    // Allow custom intervals like 2m, 10m, 45m, 3h, 8h, 2d, 1w, 1M
    if (/^[1-9][0-9]{0,3}[smhdwM]$/.test(trimmed)) {
      return trimmed as Timeframe;
    }
  }
  return '1m';
}

/**
 * Escapes characters for safe inclusion in HTML (e.g. Telegram parse_mode: 'HTML').
 */
export function escapeHtml(str: string): string {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/**
 * Allowed MIME types for custom wallpaper backgrounds.
 */
const ALLOWED_WALLPAPER_MIMES: ReadonlySet<string> = new Set<string>([
  'image/jpeg',
  'image/png',
  'image/webp',
  'image/gif',
  'video/mp4',
  'video/webm',
]);

/**
 * Allowed file extensions for wallpapers.
 */
const ALLOWED_WALLPAPER_EXTENSIONS: ReadonlySet<string> = new Set<string>([
  '.jpg',
  '.jpeg',
  '.png',
  '.webp',
  '.gif',
  '.mp4',
  '.webm',
]);

const MAX_FILE_SIZE_BYTES = 100 * 1024 * 1024; // 100MB cap for rich high-definition video loops and backgrounds

export interface FileValidationResult {
  ok: boolean;
  error?: string;
}

/**
 * Defensive validation for uploaded wallpaper/background files.
 */
export function validateWallpaperFile(file: File): FileValidationResult {
  if (!file) {
    return { ok: false, error: 'No file selected.' };
  }

  if (file.size > MAX_FILE_SIZE_BYTES) {
    return {
      ok: false,
      error: `File size exceeds maximum allowed limit of 100MB (received ${(file.size / (1024 * 1024)).toFixed(1)}MB).`,
    };
  }

  const lowerName = file.name.toLowerCase();
  const hasValidExt = Array.from(ALLOWED_WALLPAPER_EXTENSIONS).some((ext) => lowerName.endsWith(ext));
  if (!hasValidExt) {
    return {
      ok: false,
      error: 'Unsupported file extension. Allowed formats: MP4, WebM, GIF, PNG, JPG, WebP.',
    };
  }

  // Check MIME type if provided by browser
  if (file.type && !ALLOWED_WALLPAPER_MIMES.has(file.type)) {
    return {
      ok: false,
      error: `Unsupported MIME type: ${file.type}. Allowed: images (JPG, PNG, WebP, GIF) or video (MP4, WebM).`,
    };
  }

  return { ok: true };
}

/**
 * Validates and sanitizes a media URL (for wallpapers and backgrounds).
 * Rejects javascript:, file:, data: (unless safe image/video data URL), or URLs with quotes/parentheses.
 */
export function sanitizeMediaUrl(rawUrl: string | null | undefined): string | null {
  if (!rawUrl) return null;
  const trimmed = rawUrl.trim();
  if (!trimmed) return null;

  // Check for forbidden characters that could break out of CSS url("") or HTML attributes
  if (/[\r\n\t"'<>`\\]/.test(trimmed)) {
    return null;
  }

  // Handle local blob: URLs safely
  if (trimmed.startsWith('blob:')) {
    // Blob URLs generated by URL.createObjectURL start with blob:http(s)://
    try {
      const blobTarget = trimmed.slice(5);
      const parsed = new URL(blobTarget);
      if (parsed.protocol === 'http:' || parsed.protocol === 'https:') {
        return trimmed;
      }
    } catch {
      return null;
    }
    return null;
  }

  // Handle safe relative URLs (e.g. /videos/cyber_grid.mp4)
  if (trimmed.startsWith('/') && !trimmed.startsWith('//')) {
    if (/^\/[a-zA-Z0-9_\-\.\/]+$/.test(trimmed)) {
      return trimmed;
    }
    return null;
  }

  // Handle standard HTTP/HTTPS URLs
  try {
    const parsed = new URL(trimmed);
    if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
      return null;
    }
    if (!parsed.hostname || parsed.hostname.length < 3) {
      return null;
    }
    return parsed.href;
  } catch {
    return null;
  }
}

/**
 * Validates Telegram Bot API Token format.
 * Format standard: <digits 6-12>:<alphanumeric and underscores 30-50>
 */
export function validateTelegramBotToken(token: string): boolean {
  if (!token) return false;
  const trimmed = token.trim();
  const tokenRegex = /^\d{6,12}:[A-Za-z0-9_-]{30,50}$/;
  return tokenRegex.test(trimmed);
}

/**
 * Validates Telegram Chat ID format.
 * Format standard: numeric integer (positive for user, negative for group/channel)
 */
export function validateTelegramChatId(chatId: string): boolean {
  if (!chatId) return false;
  const trimmed = chatId.trim();
  const chatRegex = /^-?\d{5,16}$/;
  return chatRegex.test(trimmed);
}

/**
 * In-memory client rate limiter for outbound Telegram notifications.
 * Limits dispatches to at most 10 messages per 60 seconds rolling window.
 */
const MAX_NOTIFICATIONS_PER_MINUTE = 10;
const rollingNotificationTimestamps: number[] = [];

export function checkTelegramRateLimit(): boolean {
  const now = Date.now();
  const windowStart = now - 60000;

  // Prune timestamps older than 60 seconds
  while (
    rollingNotificationTimestamps.length > 0 &&
    rollingNotificationTimestamps[0] < windowStart
  ) {
    rollingNotificationTimestamps.shift();
  }

  if (rollingNotificationTimestamps.length >= MAX_NOTIFICATIONS_PER_MINUTE) {
    return false;
  }

  rollingNotificationTimestamps.push(now);
  return true;
}

/**
 * Validates vault payload structure before decryption attempt.
 */
export function validateVaultPayloadStructure(payload: unknown): {
  ok: boolean;
  error?: string;
  parsed?: { salt: string; iv: string; ciphertext: string };
} {
  if (!payload || typeof payload !== 'object') {
    return { ok: false, error: 'Vault payload is not a valid JSON object.' };
  }

  const p = payload as Record<string, unknown>;

  if (typeof p.salt !== 'string' || !/^[0-9a-fA-F]{32}$/.test(p.salt)) {
    return { ok: false, error: 'Invalid or corrupted salt parameter in vault payload.' };
  }

  if (typeof p.iv !== 'string' || !/^[0-9a-fA-F]{24}$/.test(p.iv)) {
    return { ok: false, error: 'Invalid or corrupted IV parameter in vault payload.' };
  }

  if (
    typeof p.ciphertext !== 'string' ||
    !/^[0-9a-fA-F]+$/.test(p.ciphertext) ||
    p.ciphertext.length < 32 ||
    p.ciphertext.length > 1000000
  ) {
    return { ok: false, error: 'Invalid ciphertext length or hex encoding in vault payload.' };
  }

  return {
    ok: true,
    parsed: {
      salt: p.salt,
      iv: p.iv,
      ciphertext: p.ciphertext,
    },
  };
}
